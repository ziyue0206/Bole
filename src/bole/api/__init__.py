"""Public adapter contracts. Plugins are discovered using Python entry points.

Register factories in bole.benchmarks, bole.harnesses or bole.policies. A benchmark
owns its instance vocabulary and native evaluation; the engine never assumes a
particular action width, reward, seed bank, or simulator package.
"""

from typing import Any, Protocol


class EnvironmentSession(Protocol):
    def open(self) -> dict: ...
    def observe(self) -> dict: ...
    def delivered(self) -> None: ...
    def execute(self, actions: list[dict], call_id: str) -> dict: ...
    def close(self, reason: str) -> dict: ...


class BenchmarkAdapter(Protocol):
    def plan(self, config: dict) -> dict: ...
    def check(self, config: dict) -> dict: ...
    def session(self, context: dict) -> EnvironmentSession: ...
    def summary(self, plan: dict, results: list[dict]) -> dict: ...


class HarnessAdapter(Protocol):
    async def open(self, context: dict, tools: Any) -> None: ...
    def bind_episode(self, store: Any, tools: Any) -> None: ...
    async def run_episode(self, prompt: str, initial_content: list, on_delivered: Any,
                          timeout_s: float | None) -> dict: ...
    async def stop_episode(self, reason: str) -> None: ...
    async def feedback(self, text: str) -> Any: ...
    async def export_asset(self, destination: Any, metadata: dict,
                           partial: bool = False) -> dict: ...
    async def close(self) -> None: ...


class PolicyAdapter(Protocol):
    """Inference only; success and action execution remain benchmark responsibilities."""
    def load(self, config: dict, resources: dict) -> None: ...
    def infer(self, observation: dict) -> dict: ...
    def close(self) -> None: ...
